#!/usr/bin/env python3
"""
Automated verification script for Phase 5 warehouse loading (DuckDB local or Redshift AWS).
Performs:
1. Metric Equivalence: Compares row counts, SUM(volume), and SUM(trade_count) between finalized Delta tables and warehouse.
2. Idempotency: Re-invokes Lambda with the same manifest; asserts row counts and metrics remain strictly unchanged.
3. Incremental State: Validates high-water mark tracking ensures re-running never re-exports already loaded windows.
4. Audit Trail: Verifies load_audit table has logged all successful runs.
"""

